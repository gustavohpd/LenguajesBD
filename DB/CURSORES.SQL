SET SERVEROUTPUT ON;

-----ESTADOS
DECLARE
    CURSOR FIDE_ESTADOS_C IS
         SELECT ESTADO_ID, 
                NOMBRE_ESTADO
                FROM FIDE_ESTADOS_TB;
BEGIN
    FOR I IN FIDE_ESTADOS_C LOOP
        DBMS_OUTPUT.PUT_LINE('ID: ' || I.ESTADO_ID || ' - ' || I.NOMBRE_ESTADO);
    END LOOP;

EXCEPTION
    WHEN NO_DATA_FOUND THEN
        DBMS_OUTPUT.PUT_LINE('No hay estados registrados.');
    WHEN OTHERS THEN
        DBMS_OUTPUT.PUT_LINE('ERROR ESTADOS: ' || SQLCODE || ' - ' || SQLERRM);
END;
/

----ROLES
DECLARE
    CURSOR FIDE_ROLES_C IS
         SELECT ROL_ID,
                NOMBRE_ROL,
                ESTADO_ID
                FROM FIDE_ROLES_TB;
BEGIN
    FOR I IN FIDE_ROLES_C LOOP
        IF I.ESTADO_ID = 1 THEN
            DBMS_OUTPUT.PUT_LINE(I.NOMBRE_ROL || ' - ACTIVO');
        ELSE
            DBMS_OUTPUT.PUT_LINE(I.NOMBRE_ROL || ' - INACTIVO');
        END IF;
    END LOOP;

EXCEPTION
    WHEN NO_DATA_FOUND THEN
        DBMS_OUTPUT.PUT_LINE('No hay roles.');
    WHEN OTHERS THEN
        DBMS_OUTPUT.PUT_LINE('ERROR ROLES: ' || SQLCODE || ' - ' || SQLERRM);
END;
/

